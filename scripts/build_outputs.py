#!/usr/bin/env python3
"""Generate import-grade outputs and validate the parakeet-corrections repo.

Run without arguments to generate outputs. Run with --check to validate only.
"""

import argparse
import json
import os
import re
import sys
import tempfile
import urllib.error
import urllib.request
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = REPO_ROOT / "data"
FORMAT_VOCAB_DIR = REPO_ROOT / "formats" / "vocabulary"
FORMAT_HANDY_DICT_DIR = REPO_ROOT / "formats" / "handy-dictionary"

SAFE_FILES = ["english.json", "tech.json", "media.json", "health.json"]
RISKY_FILE = "risky.json"
ALL_FILE = "all.json"

MAX_VALUE_LEN = 100

PRIVACY_BLOCKLIST = [
    "mervin",
    "mervyn",
    "merbin",
    "marcus",
    "marc",
    "marco",
    "marcos",
    "marge",
    "marvin",
    "jardiance",
    "jardians",
]

COMMITTED_ARTIFACTS = {
    "all.json": DATA_DIR / ALL_FILE,
    "all.txt": FORMAT_VOCAB_DIR / "all.txt",
    "dictionary.json": FORMAT_HANDY_DICT_DIR / "dictionary.json",
}


def generated_marker() -> str:
    return "# Generated by scripts/build_outputs.py — do not hand-edit.\n"


def load_json(path: Path) -> list:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def validate_safe_entries(data: list, path: Path, seen_mistranslations: dict) -> None:
    for idx, entry in enumerate(data):
        keys = set(entry.keys())
        if keys != {"mistranslation", "correction"}:
            raise ValueError(
                f"{path}: entry {idx} has keys {sorted(keys)}, expected exactly [mistranslation, correction]"
            )
        for key in ("mistranslation", "correction"):
            value = entry[key]
            if not isinstance(value, str):
                raise ValueError(f"{path}: entry {idx} {key} is not a string")
            if value.strip() == "":
                raise ValueError(f"{path}: entry {idx} {key} is empty or whitespace-only")
            if len(value) > MAX_VALUE_LEN:
                raise ValueError(
                    f"{path}: entry {idx} {key} exceeds {MAX_VALUE_LEN} chars"
                )
        mistranslation = entry["mistranslation"]
        mt_key = mistranslation.strip().lower()
        if mt_key in seen_mistranslations:
            raise ValueError(
                f"{path}: duplicate mistranslation (case-insensitive) '{mistranslation}' "
                f"also in {seen_mistranslations[mt_key]}"
            )
        seen_mistranslations[mt_key] = str(path)


def validate_risky_entries(data: list) -> None:
    for idx, entry in enumerate(data):
        keys = set(entry.keys())
        if keys != {"mistranslation", "correction", "collides_with", "note"}:
            raise ValueError(
                f"{Path('data/risky.json')}: entry {idx} has keys {sorted(keys)}, "
                f"expected exactly [mistranslation, correction, collides_with, note]"
            )
        for key in ("mistranslation", "correction", "collides_with", "note"):
            value = entry[key]
            if not isinstance(value, str):
                raise ValueError(f"{Path('data/risky.json')}: entry {idx} {key} is not a string")
            if value.strip() == "":
                raise ValueError(f"{Path('data/risky.json')}: entry {idx} {key} is empty or whitespace-only")
        # Only imported values are constrained by Handy's UI cap.
        for key in ("mistranslation", "correction"):
            if len(entry[key]) > MAX_VALUE_LEN:
                raise ValueError(
                    f"{Path('data/risky.json')}: entry {idx} {key} exceeds {MAX_VALUE_LEN} chars"
                )


def scan_privacy() -> tuple[list[str], list[str], list[str]]:
    """Return (content_violations, filename_violations, unreadable_warnings)."""
    content_violations: list[str] = []
    filename_violations: list[str] = []
    unreadable: list[str] = []
    git_dir = REPO_ROOT / ".git"
    this_script = Path(__file__).resolve()
    skip_dirs = {git_dir, REPO_ROOT / "__pycache__"}

    for root, dirs, files in os.walk(REPO_ROOT):
        # Skip .git and build-artifact directories that are not part of the source tree.
        dirs[:] = [
            d
            for d in dirs
            if Path(root) / d not in skip_dirs and d != "__pycache__"
        ]
        for name in files:
            file_path = Path(root) / name
            # The script that defines the blocklist is allowed to contain those words.
            if file_path.resolve() == this_script:
                continue
            # Skip compiled Python artifacts that mirror this script.
            if name.endswith(".pyc") and "build_outputs" in name:
                continue
            # Filename scan: word-fragment on path.name.
            name_lower = file_path.name.lower()
            for word in PRIVACY_BLOCKLIST:
                if word.lower() in name_lower:
                    filename_violations.append(
                        f"{file_path}: filename contains blocklist word '{word}'"
                    )
            # Content scan: word-boundary.
            try:
                text = file_path.read_text(encoding="utf-8", errors="replace")
            except (OSError, UnicodeDecodeError):
                unreadable.append(f"{file_path}: could not read file")
                continue
            for word in PRIVACY_BLOCKLIST:
                pattern = re.compile(r"\b" + re.escape(word) + r"\b", re.IGNORECASE)
                for _ in pattern.finditer(text):
                    content_violations.append(f"{file_path}: blocklist word '{word}'")
    return content_violations, filename_violations, unreadable


def fetch_url_text(url: str, timeout: int = 15) -> str:
    req = urllib.request.Request(
        url,
        headers={
            "User-Agent": "parakeet-corrections build_outputs.py (stdlib fetch)",
            "Accept": "text/plain, text/html, application/json",
        },
    )
    with urllib.request.urlopen(req, timeout=timeout) as response:
        return response.read().decode("utf-8", errors="replace")


def verify_handy_dictionary_csv_headers() -> bool:
    """Try to verify Handy-Dictionary's expected CSV import columns.

    Returns True only if we can find unambiguous evidence that the parser
    expects 'mistranslation' and 'correction' columns. Otherwise returns
    False so the CSV is cut rather than guessed.
    """
    try:
        readme = fetch_url_text(
            "https://raw.githubusercontent.com/pupontech/Handy-Dictionary/main/README.md"
        )
    except (urllib.error.HTTPError, urllib.error.URLError, TimeoutError, OSError):
        return False

    # Accept unambiguous mentions of the column names we want to emit.
    lower_readme = readme.lower()
    has_mistranslation = "mistranslation" in lower_readme
    has_correction = "correction" in lower_readme
    # Also require some CSV/import keyword to avoid matching unrelated prose.
    has_csv_import = any(
        kw in lower_readme
        for kw in ["csv", "import", "replace", "word replacements", "headers"]
    )
    return has_mistranslation and has_correction and has_csv_import


def csv_escape(value: str) -> str:
    if "," in value or '"' in value or "\n" in value:
        escaped = value.replace('"', '""')
        return f'"{escaped}"'
    return value


def generate_csv(all_entries: list, output_root: Path) -> None:
    handy_dict_dir = output_root / "formats" / "handy-dictionary"
    handy_dict_dir.mkdir(parents=True, exist_ok=True)
    csv_path = handy_dict_dir / "replacements.csv"
    lines = [generated_marker(), "mistranslation,correction\n"]
    for entry in all_entries:
        # Minimal CSV escaping: quote values containing comma or quote.
        mt = entry["mistranslation"]
        corr = entry["correction"]
        lines.append(f"{csv_escape(mt)},{csv_escape(corr)}\n")
    csv_path.write_text("".join(lines), encoding="utf-8")


def generate_vocabulary(all_entries: list, output_root: Path) -> Path:
    vocab_dir = output_root / "formats" / "vocabulary"
    vocab_dir.mkdir(parents=True, exist_ok=True)
    corrections = [entry["correction"] for entry in all_entries]
    seen = set()
    deduped = []
    for c in corrections:
        key = c.strip().lower()
        if key not in seen:
            seen.add(key)
            deduped.append(c)
    vocab_path = vocab_dir / "all.txt"
    vocab_path.write_text(
        generated_marker() + "\n".join(deduped) + "\n",
        encoding="utf-8",
    )
    return vocab_path


def generate_dictionary(all_entries: list, output_root: Path) -> Path:
    handy_dict_dir = output_root / "formats" / "handy-dictionary"
    handy_dict_dir.mkdir(parents=True, exist_ok=True)
    data = {
        "schema": "handy-dictionary",
        "version": 1,
        "customWords": [],
        "replacements": [
            {"from": entry["mistranslation"], "to": entry["correction"]}
            for entry in all_entries
        ],
    }
    dict_path = handy_dict_dir / "dictionary.json"
    dict_path.write_text(
        json.dumps(data, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    return dict_path


def generate_all_json(all_entries: list, output_root: Path) -> Path:
    data_dir = output_root / "data"
    data_dir.mkdir(parents=True, exist_ok=True)
    all_path = data_dir / ALL_FILE
    all_path.write_text(
        json.dumps(all_entries, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    return all_path


def generate_outputs(all_entries: list, output_root: Path) -> dict[str, Path]:
    """Generate all tracked artifacts under output_root and return their paths."""
    return {
        "all.json": generate_all_json(all_entries, output_root),
        "all.txt": generate_vocabulary(all_entries, output_root),
        "dictionary.json": generate_dictionary(all_entries, output_root),
    }


def validate_dictionary_schema(path: Path) -> None:
    with path.open("r", encoding="utf-8") as f:
        data = json.load(f)
    if not isinstance(data, dict):
        raise ValueError(f"{path}: dictionary.json root is not an object")
    if data.get("schema") != "handy-dictionary":
        raise ValueError(f"{path}: dictionary.json missing/invalid 'schema'")
    if data.get("version") != 1:
        raise ValueError(f"{path}: dictionary.json missing/invalid 'version'")
    replacements = data.get("replacements")
    if not isinstance(replacements, list):
        raise ValueError(f"{path}: dictionary.json 'replacements' is not an array")
    for idx, pair in enumerate(replacements):
        if not isinstance(pair, dict):
            raise ValueError(f"{path}: replacements[{idx}] is not an object")
        for key in ("from", "to"):
            value = pair.get(key)
            if not isinstance(value, str) or value.strip() == "":
                raise ValueError(
                    f"{path}: replacements[{idx}] has missing/empty '{key}'"
                )


def validate(check_only: bool) -> bool:
    """Run all validation rules. Returns True if clean."""
    # Validate safe files and collect entries for all.json.
    seen_mistranslations: dict[str, str] = {}
    all_entries: list = []
    for filename in SAFE_FILES:
        path = DATA_DIR / filename
        if not path.exists():
            raise FileNotFoundError(f"Missing required data file: {path}")
        data = load_json(path)
        validate_safe_entries(data, path, seen_mistranslations)
        all_entries.extend(data)

    # Validate risky file.
    risky_path = DATA_DIR / RISKY_FILE
    if risky_path.exists():
        risky_data = load_json(risky_path)
        validate_risky_entries(risky_data)
        risky_mistranslations = {entry["mistranslation"] for entry in risky_data}
    else:
        risky_mistranslations = set()

    # Ensure risky entries never leaked into all.json.
    all_mistranslations = {entry["mistranslation"] for entry in all_entries}
    leaked = all_mistranslations & risky_mistranslations
    if leaked:
        raise ValueError(
            f"Risky mistranslations leaked into safe all.json: {sorted(leaked)}"
        )

    # Privacy scan.
    content_violations, filename_violations, unreadable = scan_privacy()
    if unreadable:
        for warning in unreadable:
            print(f"WARNING: {warning}", file=sys.stderr)
    privacy_violations = content_violations + filename_violations
    if privacy_violations:
        print("PRIVACY BLOCKLIST FAILURES:", file=sys.stderr)
        for v in privacy_violations:
            print(f"  {v}", file=sys.stderr)
        raise ValueError("Privacy blocklist scan failed")
    if unreadable and check_only:
        raise ValueError("Privacy scan failed: unreadable files encountered")

    if check_only:
        # Drift guard: regenerate to a temp dir and byte-compare against committed files.
        with tempfile.TemporaryDirectory() as tmpdir:
            tmp_root = Path(tmpdir)
            generated_paths = generate_outputs(all_entries, tmp_root)
            drift_errors: list[str] = []
            for name, committed_path in COMMITTED_ARTIFACTS.items():
                generated_path = generated_paths[name]
                if not committed_path.exists():
                    drift_errors.append(f"{committed_path}: missing committed artifact")
                    continue
                if committed_path.read_bytes() != generated_path.read_bytes():
                    drift_errors.append(
                        f"{committed_path}: generated content differs from committed file"
                    )
            if drift_errors:
                raise ValueError("Drift guard failed:\n" + "\n".join(drift_errors))
            validate_dictionary_schema(generated_paths["dictionary.json"])
    else:
        # Generate outputs in the repo and validate the new dictionary schema.
        generated_paths = generate_outputs(all_entries, REPO_ROOT)
        validate_dictionary_schema(generated_paths["dictionary.json"])

        if verify_handy_dictionary_csv_headers():
            generate_csv(all_entries, REPO_ROOT)
        else:
            csv_path = FORMAT_HANDY_DICT_DIR / "replacements.csv"
            if csv_path.exists():
                csv_path.unlink()
            print(
                "CSV generation skipped: Handy-Dictionary import headers could not be verified.",
                file=sys.stderr,
            )

    return True


def main() -> int:
    parser = argparse.ArgumentParser(description="Build and validate outputs.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Validate only; do not write generated files.",
    )
    args = parser.parse_args()

    try:
        validate(args.check)
    except Exception as exc:
        print(f"VALIDATION FAILED: {exc}", file=sys.stderr)
        return 1

    if args.check:
        print("All validations passed.")
    else:
        print("Outputs generated and validated.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
